function initLoader() {
    const loader = document.getElementById('loader');
    const loaderPercent = document.getElementById('loaderPercent');
    const loaderProgress = document.querySelector('.loader-progress');

    if (!loader || !loaderPercent || !loaderProgress) return;

    let progress = 0;
    const loading = setInterval(() => {
        progress += Math.floor(Math.random() * 8) + 2;

        if (progress >= 100) {
            progress = 100;
            clearInterval(loading);
            setTimeout(() => loader.classList.add('hidden'), 450);
        }

        loaderPercent.textContent = progress;
        loaderProgress.style.width = `${progress}%`;
    }, 90);
}

function initCursor() {
    const cursor = document.querySelector('.cursor');
    const follower = document.querySelector('.cursor-follower');

    if (!cursor || !follower || !window.matchMedia('(pointer: fine)').matches) {
        if (cursor) cursor.style.display = 'none';
        if (follower) follower.style.display = 'none';
        return;
    }

    let mouseX = 0;
    let mouseY = 0;
    let followerX = 0;
    let followerY = 0;

    document.addEventListener('mousemove', (event) => {
        mouseX = event.clientX;
        mouseY = event.clientY;
        cursor.style.left = `${mouseX}px`;
        cursor.style.top = `${mouseY}px`;
    });

    function animateCursor() {
        followerX += (mouseX - followerX) * 0.12;
        followerY += (mouseY - followerY) * 0.12;
        follower.style.left = `${followerX}px`;
        follower.style.top = `${followerY}px`;
        requestAnimationFrame(animateCursor);
    }

    animateCursor();

    document.querySelectorAll('a, button, .project-card, .service-card, .social-card').forEach((element) => {
        element.addEventListener('mouseenter', () => cursor.classList.add('active'));
        element.addEventListener('mouseleave', () => cursor.classList.remove('active'));
    });
}

function initTyping() {
    const typingElement = document.getElementById('typing');
    if (!typingElement) return;

    const roles = ['Developer', 'Creative Coder', 'Designer', 'Video Editor', 'Problem Solver'];
    let roleIndex = 0;
    let charIndex = 0;
    let deleting = false;

    function typeEffect() {
        const currentRole = roles[roleIndex];

        if (!deleting) {
            typingElement.textContent = currentRole.substring(0, charIndex + 1);
            charIndex += 1;

            if (charIndex === currentRole.length) {
                deleting = true;
                setTimeout(typeEffect, 1450);
                return;
            }
        } else {
            typingElement.textContent = currentRole.substring(0, charIndex - 1);
            charIndex -= 1;

            if (charIndex === 0) {
                deleting = false;
                roleIndex = (roleIndex + 1) % roles.length;
            }
        }

        setTimeout(typeEffect, deleting ? 50 : 90);
    }

    typeEffect();
}

